#!/bin/bash
# Creates "Cursor Pocket.app", a tiny launcher that opens Cursor WITH the local debug port (phone actions need it).
# Use it instead of the normal Cursor icon (Dock, Spotlight, Launchpad). It changes no Cursor setting and no file in ~/.cursor.
#
#   tools/mac/make-launcher.sh              create it in ~/Applications (or $CP_LAUNCHER_DIR)
#   tools/mac/make-launcher.sh --remove     delete it
#
# What the launcher does when you open it:
#  - Cursor closed: starts it with --remote-debugging-port=9222.
#  - Cursor already open WITH the port: just brings it to the front.
#  - Cursor already open WITHOUT the port: tells you so and does NOT restart it (that would interrupt running chats).
#
# Limits: Cursor's own self-update restarts it without the port, and so does a Cursor opened some other way (Dock, `cursor .`).
# The Settings screen of the app and `npm run doctor` tell you when that happened.
set -euo pipefail

NAME="Cursor Pocket"
DEST_DIR="${CP_LAUNCHER_DIR:-$HOME/Applications}"
APP="$DEST_DIR/$NAME.app"
PORT="${CP_CDP_PORT:-9222}"
CURSOR_APP="${CP_CURSOR_APP:-/Applications/Cursor.app}"

if [ "${1:-}" = "--remove" ]; then
  if [ -d "$APP" ]; then
    rm -rf "$APP"
    echo "Removed $APP"
  else
    echo "Nothing to remove: $APP does not exist."
  fi
  exit 0
fi

[ -d "$CURSOR_APP" ] || { echo "Cursor not found at $CURSOR_APP (set CP_CURSOR_APP)." >&2; exit 1; }

rm -rf "$APP"
mkdir -p "$APP/Contents/MacOS" "$APP/Contents/Resources"

# Same icon as Cursor, so the Dock does not get a second, different-looking one.
ICON="$(/usr/libexec/PlistBuddy -c 'Print :CFBundleIconFile' "$CURSOR_APP/Contents/Info.plist" 2>/dev/null || true)"
ICON="${ICON%.icns}"
if [ -n "$ICON" ] && [ -f "$CURSOR_APP/Contents/Resources/$ICON.icns" ]; then
  cp "$CURSOR_APP/Contents/Resources/$ICON.icns" "$APP/Contents/Resources/launcher.icns"
fi

cat > "$APP/Contents/Info.plist" <<PLIST
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>CFBundleName</key><string>$NAME</string>
  <key>CFBundleDisplayName</key><string>$NAME</string>
  <key>CFBundleIdentifier</key><string>local.cursor-pocket.launcher</string>
  <key>CFBundleExecutable</key><string>launch</string>
  <key>CFBundleIconFile</key><string>launcher</string>
  <key>CFBundlePackageType</key><string>APPL</string>
  <key>CFBundleShortVersionString</key><string>1.0</string>
  <key>LSUIElement</key><true/>
</dict>
</plist>
PLIST

cat > "$APP/Contents/MacOS/launch" <<'SCRIPT'
#!/bin/bash
# Cursor Pocket launcher (generated by tools/mac/make-launcher.sh).
PORT="${CP_CDP_PORT:-__PORT__}"
CURSOR_APP="${CP_CURSOR_APP:-__CURSOR_APP__}"
URL="http://127.0.0.1:${PORT}/json/version"

port_up() { curl -fsS --max-time 1 "$URL" >/dev/null 2>&1; }
# Only the executable path is looked at (never the command line: it contains keys).
cursor_running() { ps -axo comm= | awk '/\/Cursor\.app\/Contents\/MacOS\/Cursor$/ { found = 1 } END { exit !found }'; }
act() { if [ -n "${CP_LAUNCHER_DRYRUN:-}" ]; then echo "would: $*"; else "$@"; fi; }

if port_up; then
  act open -a "$CURSOR_APP"
elif cursor_running; then
  act osascript -e 'display dialog "Cursor is already open without the debug port, so the phone cannot answer or send messages.\n\nWhen your agents have finished, quit Cursor (Cmd+Q) and open Cursor Pocket again. It is not restarted automatically because that would interrupt running chats." with title "Cursor Pocket" buttons {"OK"} default button "OK" with icon note giving up after 60' >/dev/null
  act open -a "$CURSOR_APP"
else
  act open -a "$CURSOR_APP" --args "--remote-debugging-port=${PORT}"
fi
SCRIPT
# Bake in the values this launcher was made with (still overridable through the environment).
sed -i '' -e "s|__PORT__|$PORT|" -e "s|__CURSOR_APP__|$CURSOR_APP|" "$APP/Contents/MacOS/launch"
chmod +x "$APP/Contents/MacOS/launch"

# Tell LaunchServices about the new app (Spotlight, Launchpad); harmless if it fails.
/System/Library/Frameworks/CoreServices.framework/Frameworks/LaunchServices.framework/Support/lsregister -f "$APP" >/dev/null 2>&1 || true

echo "Created $APP"
echo "Open it from Spotlight or drag it to the Dock in place of Cursor. If Cursor is open now, nothing changes until you quit it."
