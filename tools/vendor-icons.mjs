#!/usr/bin/env node
// Extract a reduced icon set from an EXISTING `lucide-react` package on disk (ISC license)
// and generate `pwa/js/icons.js` (SVG data, no runtime dependency) plus the license in `pwa/icons/`.
//
// Usage:  node tools/vendor-icons.mjs <path>/node_modules/lucide-react
//
// Icons are not hand-drawn: paths come from the library. To change an icon, edit ICONS and re-run.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const src = process.argv[2];
if (!src) {
  console.error('Usage: node tools/vendor-icons.mjs <path>/node_modules/lucide-react');
  process.exit(2);
}

// internal name -> Lucide name
const ICONS = {
  question: 'circle-question-mark',
  terminal: 'terminal',
  plan: 'clipboard-list',
  alert: 'triangle-alert',
  info: 'info',
  chevronRight: 'chevron-right',
  chevronDown: 'chevron-down',
  chevronUp: 'chevron-up',
  back: 'arrow-left',
  folder: 'folder',
  folderOpen: 'folder-open',
  bell: 'bell',
  bellOff: 'bell-off',
  stop: 'square',
  zap: 'zap',
  settings: 'settings',
  home: 'house',
  refresh: 'refresh-cw',
  spinner: 'loader-circle',
  check: 'check',
  checkCircle: 'circle-check',
  eyeOff: 'eye-off',
  restore: 'rotate-ccw',
  logout: 'log-out',
  offline: 'wifi-off',
  phone: 'smartphone',
  clock: 'clock',
  close: 'x',
  database: 'database',
  share: 'square-arrow-up',
  lock: 'lock',
  // Phase 2 (actions)
  arrowUp: 'arrow-up',
  send: 'send',
  skip: 'skip-forward',
  plug: 'plug',
  message: 'message-square',
  pencil: 'pencil',
  // Tool approval (command, edit, MCP...)
  approval: 'shield-question-mark',
  // Recent activity (tool categories)
  fileText: 'file-text',
  search: 'search',
  globe: 'globe',
  wrench: 'wrench',
  bot: 'bot',
  listTodo: 'list-todo',
  trash: 'trash-2',
  user: 'user',
  xCircle: 'circle-x',
  // Navigation and favorites
  inbox: 'inbox',
  messages: 'messages-square',
  heart: 'heart',
  heartOff: 'heart-off',
  plus: 'plus',
  image: 'image',
  pin: 'pin',
  pinOff: 'pin-off',
  branch: 'git-branch',
  cpu: 'cpu',
  archive: 'archive',
  archiveRestore: 'archive-restore',
  stop: 'square',
  volumeOff: 'volume-x',
};

const pkg = JSON.parse(fs.readFileSync(path.join(src, 'package.json'), 'utf8'));
const out = {};
for (const [name, lucide] of Object.entries(ICONS)) {
  const file = path.join(src, 'dist', 'esm', 'icons', `${lucide}.mjs`);
  const mod = await import(pathToFileURL(file).href);
  // __iconNode: [["path", {d, key}], ...] -> drop `key` (React-only)
  out[name] = mod.__iconNode.map(([tag, attrs]) => {
    const { key: _key, ...rest } = attrs;
    return [tag, rest];
  });
}

const body = `// GENERATED by tools/vendor-icons.mjs - do not edit by hand.
// Icons: Lucide ${pkg.version} (ISC license, see /icons/LICENSE-lucide.txt). No runtime dependency.
const NS = 'http://www.w3.org/2000/svg';

const DATA = ${JSON.stringify(out, null, 1)};

/** Create a decorative <svg> element for icon \`name\`. */
export function icon(name, { size = 20, className = '' } = {}) {
  const nodes = DATA[name];
  if (!nodes) throw new Error(\`unknown icon: \${name}\`);
  const svg = document.createElementNS(NS, 'svg');
  const attrs = { width: size, height: size, viewBox: '0 0 24 24', fill: 'none', stroke: 'currentColor', 'stroke-width': 2, 'stroke-linecap': 'round', 'stroke-linejoin': 'round', 'aria-hidden': 'true', focusable: 'false' };
  for (const [k, v] of Object.entries(attrs)) svg.setAttribute(k, String(v));
  svg.setAttribute('class', \`icon\${className ? \` \${className}\` : ''}\`);
  for (const [tag, a] of nodes) {
    const el = document.createElementNS(NS, tag);
    for (const [k, v] of Object.entries(a)) el.setAttribute(k, String(v));
    svg.appendChild(el);
  }
  return svg;
}

export const ICON_NAMES = Object.keys(DATA);
`;

fs.mkdirSync(path.join(root, 'pwa', 'js'), { recursive: true });
fs.mkdirSync(path.join(root, 'pwa', 'icons'), { recursive: true });
fs.writeFileSync(path.join(root, 'pwa', 'js', 'icons.js'), body);
fs.copyFileSync(path.join(src, 'LICENSE'), path.join(root, 'pwa', 'icons', 'LICENSE-lucide.txt'));
console.log(`Vendored icons: ${Object.keys(out).length} (Lucide ${pkg.version})`);
